class TestBothFormsPresentWarning:

    def test_is_subclass_of_user_warning(self):
        assert issubclass(BothFormsPresentWarning, UserWarning)

    def test_has_json_path_and_yaml_path_attributes(self, tmp_path):
        jp = tmp_path / "bib.json"
        yp = tmp_path / "bib.yaml"
        w = BothFormsPresentWarning(jp, yp)
        assert w.json_path == jp
        assert w.yaml_path == yp

    def test_str_representation_is_informative(self, tmp_path):
        jp = tmp_path / "bib.json"
        yp = tmp_path / "bib.yaml"
        w = BothFormsPresentWarning(jp, yp)
        msg = str(w)
        assert "bib.json" in msg
        assert "bib.yaml" in msg

    def test_can_be_caught_as_user_warning(self, tmp_path):
        ad = _make_analysis_dir(tmp_path)
        _write_yaml(ad / "bib.yaml", _SAMPLE_BIB)
        _write_json(ad / "bib.json", _SAMPLE_BIB)
        caught = []
        with warnings.catch_warnings(record=True) as w:
            warnings.simplefilter("always", UserWarning)
            read_bib(ad)
            caught = [x for x in w if issubclass(x.category, UserWarning)]
        assert len(caught) >= 1

    def test_can_be_filtered_separately(self, tmp_path):
        """Callers should be able to silence BothFormsPresentWarning independently."""
        ad = _make_analysis_dir(tmp_path)
        _write_yaml(ad / "bib.yaml", _SAMPLE_BIB)
        _write_json(ad / "bib.json", _SAMPLE_BIB)
        with warnings.catch_warnings(record=True) as caught_all:
            warnings.simplefilter("always")
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", BothFormsPresentWarning)
                read_bib(ad)
        bfp = [w for w in caught_all if issubclass(w.category, BothFormsPresentWarning)]
        assert not bfp


