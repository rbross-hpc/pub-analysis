class TestFormatEquivalence:
    """Both format readers must return the same logical data."""

    def test_bib_yaml_and_json_return_equivalent_data(self, tmp_path):
        ad_yaml = tmp_path / "yaml_paper.puba"
        ad_json = tmp_path / "json_paper.puba"
        ad_yaml.mkdir()
        ad_json.mkdir()

        data = {**_SAMPLE_BIB, "authors": ["Alice", "Bob"], "year": 2024}
        _write_yaml(ad_yaml / "bib.yaml", data)
        _write_json(ad_json / "bib.json", data)

        result_yaml = read_bib(ad_yaml)
        result_json = read_bib(ad_json)

        assert result_yaml is not None
        assert result_json is not None
