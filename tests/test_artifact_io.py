def _write_yaml(path: Path, data: dict, header: str = "") -> None:
    """Helper: write a dict as YAML (optionally with a comment header)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.dump(data, allow_unicode=True, sort_keys=False, default_flow_style=False)
    path.write_text(header + body, encoding="utf-8")


def _write_json(path: Path, data: dict) -> None:
    """Helper: write a dict as JSON."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2), encoding="utf-8")


def _make_analysis_dir(tmp_path: Path) -> Path:
    ad = tmp_path / "paper.puba"
    ad.mkdir()
    return ad


